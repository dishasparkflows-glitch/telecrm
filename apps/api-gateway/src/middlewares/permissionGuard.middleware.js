const axios = require('axios');
const { env } = require('@sparkcrm/shared-config');
const { ROLES } = require('@sparkcrm/shared-utils');
const { createServiceHeaders } = require('@sparkcrm/shared-middleware');

/**
 * Permission Guard Middleware — Checks per-module CRUD permissions
 * 
 * Maps HTTP methods to required actions:
 *   GET    → view
 *   POST   → create
 *   PUT    → edit
 *   PATCH  → edit
 *   DELETE → delete
 * 
 * Superadmin bypasses all permission checks.
 * Admin bypasses all permission checks (broad access role).
 * 
 * IMPORTANT: Even when bypassing checks, we still fetch and forward
 * permissions via x-user-permissions header so downstream services
 * (especially buildScopeFilter) can use isOwn/isGlobal flags for
 * proper data scoping.
 */

// Cache role permissions (short TTL to pick up admin changes quickly)
const rolePermCache = new Map();
const CACHE_TTL = 30 * 1000; // 30 seconds

const METHOD_TO_ACTION = {
    GET: 'view',
    HEAD: 'view',
    POST: 'create',
    PUT: 'edit',
    PATCH: 'edit',
    DELETE: 'delete',
};

/**
 * Clear permission cache for a specific role (or all roles)
 */
function clearPermCache(roleId) {
    if (roleId) {
        rolePermCache.delete(roleId);
    } else {
        rolePermCache.clear();
    }
}

/**
 * Fetch role permissions from tenant-service (with caching)
 */
async function getRolePermissions(roleId) {
    if (!roleId) return null;

    const cached = rolePermCache.get(roleId);
    if (cached && Date.now() - cached.ts < CACHE_TTL) {
        return cached.data;
    }

    try {
        const path = `/internal/roles/${encodeURIComponent(String(roleId))}`;
        const headers = createServiceHeaders({
            issuer: 'api-gateway',
            audience: 'tenant-service',
            method: 'GET',
            path,
        });
        const response = await axios.get(
            `${env.SERVICES.TENANT}${path}`,
            { timeout: 3000, headers }
        );
        if (response.data.success) {
            const role = response.data.data;
            const permissions = role.permissions || {};
            rolePermCache.set(roleId, { data: permissions, slug: role.slug, ts: Date.now() });
            return permissions;
        }
    } catch (err) {
        console.error('⚠️ Permission guard: failed to fetch role permissions:', err.message);
    }

    return null;
}

/**
 * Helper: fetch permissions and forward them to downstream services
 * This is called for ALL users (including superadmin/admin bypass)
 * so that buildScopeFilter can use isOwn/isGlobal for data scoping.
 */
async function forwardPermissions(req) {
    const roleId = req.userRoleId || req.headers['x-user-role-id'];
    if (!roleId) return;

    const permissions = await getRolePermissions(roleId);
    if (permissions) {
        req.headers['x-user-permissions'] = JSON.stringify(permissions);
    }
}

/**
 * Create a permission guard for a specific module
 */
const permissionGuard = (moduleKey) => {
    return async (req, res, next) => {
        try {
            // Permission context is trusted only when generated by this guard.
            delete req.headers['x-user-permissions'];

            // If no module specified, pass through
            if (!moduleKey) return next();

            const userRole = req.userRole || req.headers['x-user-role'];

            // Superadmin bypasses permission checks but still forwards permissions
            if (userRole === ROLES.SUPER_ADMIN) {
                await forwardPermissions(req);
                return next();
            }

            // Admin bypasses permission checks but still forwards permissions
            if (userRole === ROLES.ADMIN) {
                await forwardPermissions(req);
                return next();
            }

            const roleId = req.userRoleId || req.headers['x-user-role-id'];

            if (!roleId) {
                console.warn(`⚠️ [PERM] No roleId for user role=${userRole}, module=${moduleKey}`);
                return res.status(403).json({
                    success: false,
                    message: 'A valid role assignment is required',
                    code: 'ROLE_ASSIGNMENT_REQUIRED',
                });
            }

            // Determine required action from HTTP method
            const action = METHOD_TO_ACTION[req.method] || 'view';

            // Fetch role permissions
            const permissions = await getRolePermissions(roleId);
            if (!permissions) {
                console.warn(`⚠️ [PERM] Could not fetch permissions for roleId=${roleId}`);
                return res.status(503).json({
                    success: false,
                    message: 'Authorization service is temporarily unavailable',
                    code: 'AUTHORIZATION_UNAVAILABLE',
                });
            }

            // Check if the module permission allows the action
            const modulePerm = permissions[moduleKey];
            if (!modulePerm || modulePerm[action] !== true) {
                console.log(`❌ [PERM] DENIED: user=${req.headers['x-user-id']}, role=${userRole}, roleId=${roleId}, module=${moduleKey}, action=${action}, perm=${JSON.stringify(modulePerm || 'NONE')}`);
                return res.status(403).json({
                    success: false,
                    message: `You don't have '${action}' permission for '${moduleKey}'.`,
                    code: 'PERMISSION_DENIED',
                    requiredPermission: { module: moduleKey, action },
                    action,
                    module: moduleKey,
                });
            }

            // Permission granted — forward permissions to downstream services
            req.headers['x-user-permissions'] = JSON.stringify(permissions);

            next();
        } catch (error) {
            console.error('❌ Permission guard error:', error.message);
            next(error);
        }
    };
};

module.exports = { permissionGuard, clearPermCache };
